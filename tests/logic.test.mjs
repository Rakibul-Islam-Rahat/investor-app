import crypto from "node:crypto";
import { sha256 } from "../src/lib/sha256.js";
import { api, previewAllocation } from "../src/services/api.js";
import { getState } from "../src/services/mock/store.js";
import { availableOf, balanceOf } from "../src/services/ledger.js";
import assert from "node:assert";
for (const s of ["", "abc", "x".repeat(1000), "বাংলা ৳"]) assert.equal(sha256(s), crypto.createHash("sha256").update(s).digest("hex"));
let s = getState();
console.log("u1 balance", balanceOf(s.transactions,"u1")/100, "available", availableOf(s.transactions,"u1")/100);
await api.invest("u1","p2",10); s=getState();
assert.equal(s.projects.find(p=>p.id==="p2").availableUnits,130);
await assert.rejects(()=>api.invest("u7","p2",1),/KYC/);
await assert.rejects(()=>api.invest("u1","p2",9999),/available/);
await assert.rejects(()=>api.invest("u1","p4",1),/not open/);
await assert.rejects(()=>api.requestWithdraw("u5",{amount:1e12,channel:"BANK",account:"x"}),/exceeds/);
const pv = previewAllocation(s,{projectId:"p1",gross:6000000*100,costs:500000*100,commissionPct:2});
assert.equal(pv.rows.reduce((a,r)=>a+r.payout,0), pv.net);
console.log("p1 net", pv.net/100, "payouts", pv.rows.map(r=>r.payout/100));
const before = s.transactions.reduce((a,t)=>a+(t.status==="COMPLETED"?t.amount:0),0);
await api.allocate("u3",{projectId:"p1",gross:6000000*100,costs:500000*100,commissionPct:2}); s=getState();
assert.equal(s.projects.find(p=>p.id==="p1").status,"LIQUIDATED");
console.log("ledger delta", (s.transactions.reduce((a,t)=>a+(t.status==="COMPLETED"?t.amount:0),0)-before)/100, "expected", pv.net/100);
await assert.rejects(()=>api.allocate("u3",{projectId:"p1",gross:1,costs:0,commissionPct:0}),/in progress|exceed/);
console.log("ALL OK");
